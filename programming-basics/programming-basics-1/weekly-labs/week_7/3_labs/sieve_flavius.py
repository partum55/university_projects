"""
This module provides a function to generate a list of lucky numbers using
the Sieve of Flavius Josephus method. Lucky numbers are generated by iteratively
removing elements from a sequence of odd numbers, based on their positions.
"""


def sieve_flavius(n: int) -> list[int]:
    """
    Generates a list of lucky numbers not exceeding the given number n.
    Lucky numbers are generated by repeatedly removing elements based on the position
    of previous lucky numbers, similar to the Sieve of Eratosthenes used for primes.

    :param n: The upper limit for generating lucky numbers.
        All lucky numbers returned will be less than or equal to n.
    :type n: int

    :returns: A list of lucky numbers up to n.
    :rtype: list[int]

    :example:

    >>> sieve_flavius(100)
    [1, 3, 7, 9, 13, 15, 21, 25, 31, 33, 37, 43, 49, 51, 63, 67, 69, 73, 75, 79, 87, 93, 99]

    >>> sieve_flavius(33)
    [1, 3, 7, 9, 13, 15, 21, 25, 31, 33]

    >>> sieve_flavius(10)
    [1, 3, 7, 9]

    >>> sieve_flavius(0)
    []

    Notes:
    - Lucky numbers are defined by an iterative sieving process similar
        to the Sieve of Eratosthenes for primes.
    - The process starts with a list of all odd numbers and removes
        every k-th number, where k is a lucky number found in earlier steps.
    - If `n` is less than 1, the function returns an empty list.

    """
    numbers = [i for i in range(1, n + 1, 2)]
    i = 1
    while i < len(numbers):
        step = numbers[i]
        if step > len(numbers):
            break
        numbers = [num for j, num in enumerate(numbers) if (j + 1) % step != 0]
        i += 1
    return numbers


